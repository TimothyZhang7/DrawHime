async function main() {
  console.log('[seed] 开始创建默认模板...');

  // 查找管理员用户（用于模板归属）
  let admin = await prisma.user.findFirst({ where: { role: 'admin' } });
  if (!admin) {
    console.log('[seed] 未找到管理员，创建默认管理员...');
    admin = await prisma.user.create({
      data: {
        username: 'admin',
        email: 'admin@aiimage.local',
        passwordHash: await bcrypt.hash(process.env.SEED_ADMIN_PASSWORD ?? 'change-me-admin-password', 10),
        role: 'admin',
        emailVerified: true,
      },
    });
    console.log('[seed] 管理员已创建 (id:', admin.id, ')');
  }

  let created = 0;
  let skipped = 0;

  for (const tpl of SEED_TEMPLATES) {
    const existing = await prisma.template.findFirst({ where: { name: tpl.name, userId: admin.id } });
    if (existing) {
      skipped++;
      continue;
    }
    await prisma.template.create({
      data: {
        userId: admin.id,
        name: tpl.name,
        description: tpl.description,
        promptTemplate: tpl.promptTemplate,
        coverImageUrls: JSON.stringify(tpl.coverImageUrls),
        isPublic: tpl.isPublic,
      },
    });
    created++;
  }

  console.log(`[seed] 完成: 创建 ${created} 个模板, 跳过 ${skipped} 个 (已存在)`);
  await prisma.$disconnect();
}

